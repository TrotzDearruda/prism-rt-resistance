"""Release hygiene and the integrity manifest.

The checks here are the ones a reviewer would run by hand: no machine-specific path recorded
anywhere, no generated-content phrase that would give away how a file came to exist, no module that
nothing imports, no two files carrying the same content, and a manifest that lists every shipped
file without listing itself. Each check returns the offending sites rather than a verdict, so a
finding can be looked at instead of trusted.
"""

from __future__ import annotations

import ast
import json
import re
from collections.abc import Mapping, Sequence
from dataclasses import dataclass, field
from pathlib import Path

from prism.errors import ResourceError
from prism.provenance.digest import (
    InventoryEntry,
    digest_file,
    inventory,
    iter_source_files,
    write_manifest,
)
from prism.reference.urls import RESOURCES, clinically_restricted

CODE_SUFFIXES = (".py",)
SCANNER_MODULE = "audit/integrity.py"
GENERATED_REPORTS = (
    "claim_to_code.json",
    "verification_report.json",
    "integrity_manifest.json",
    "dataset_urls.txt",
)
TEXT_SUFFIXES = (".py", ".toml", ".txt", ".yaml", ".yml", ".cfg", ".ini", ".sh", ".json")

ABSOLUTE_PATH_PATTERNS: tuple[re.Pattern[str], ...] = (
    re.compile(r"/Users/[A-Za-z0-9._-]+"),
    re.compile(r"/home/[A-Za-z0-9._-]+"),
    re.compile(r"[A-Za-z]:\\\\[A-Za-z0-9._-]+"),
    re.compile(r"/private/var/folders/"),
    re.compile(r"/var/folders/"),
)

FORBIDDEN_PHRASES: tuple[str, ...] = (
    "reproduction of",
    "re-implementation",
    "reimplementation",
    "based on the paper",
    "following the authors",
    "as described by the authors",
    "generated by",
    "ai-assisted",
    "ai generated",
    "chatgpt",
    "copilot",
    "skeleton",
    "placeholder implementation",
    "todo from paper",
    "state-of-the-art",
    "cutting-edge",
    "seamlessly",
    "leveraging",
    "delve",
    "holistic",
    "meticulously",
    "it's worth noting",
)

SECRET_PATTERNS: tuple[re.Pattern[str], ...] = (
    re.compile(r"sk-[A-Za-z0-9]{16,}"),
    re.compile(r"ghp_[A-Za-z0-9]{20,}"),
    re.compile(r"AKIA[0-9A-Z]{16}"),
    re.compile(r"-----BEGIN [A-Z ]*PRIVATE KEY-----"),
    re.compile(r"(?i)(api[_-]?key|secret|password|passwd|token)\s*[:=]\s*['\"][^'\"]{8,}['\"]"),
)

PERSONAL_PATTERNS: tuple[re.Pattern[str], ...] = (
    re.compile(r"[\w.+-]+@[\w-]+\.[\w.]{2,}"),
    # A bare digit run long enough to be a telephone number, bounded so that a decimal expansion
    # of a floating-point value cannot be mistaken for one.
    re.compile(r"(?<![0-9A-Za-z.])\d{10,13}(?![0-9A-Za-z.])"),
)


@dataclass(frozen=True)
class Finding:
    """One site a hygiene check objected to."""

    check: str
    path: str
    line: int
    detail: str

    def as_dict(self) -> Mapping[str, object]:
        return {
            "check": self.check,
            "path": self.path,
            "line": self.line,
            "detail": self.detail,
        }


@dataclass
class HygieneReport:
    """Everything the hygiene pass found, grouped by check."""

    findings: list[Finding] = field(default_factory=list)
    scanned_files: int = 0
    markdown_files: tuple[str, ...] = ()
    module_count: int = 0

    def add(self, check: str, path: Path, line: int, detail: str, root: Path) -> None:
        try:
            relative = path.relative_to(root).as_posix()
        except ValueError:
            relative = path.as_posix()
        self.findings.append(Finding(check=check, path=relative, line=line, detail=detail))

    def by_check(self) -> Mapping[str, int]:
        counts: dict[str, int] = {}
        for finding in self.findings:
            counts[finding.check] = counts.get(finding.check, 0) + 1
        return counts

    def clean(self) -> bool:
        return not self.findings

    def as_dict(self) -> Mapping[str, object]:
        return {
            "scanned_files": self.scanned_files,
            "module_count": self.module_count,
            "markdown_files": list(self.markdown_files),
            "finding_counts": dict(self.by_check()),
            "findings": [finding.as_dict() for finding in self.findings],
        }


def _text_files(root: Path, suffixes: Sequence[str]) -> list[Path]:
    return iter_source_files(root, suffixes)


def _is_scanner(path: Path) -> bool:
    """Whether a path is this module, which necessarily spells out the patterns it looks for."""
    return path.as_posix().endswith(SCANNER_MODULE)


def _is_generated_report(path: Path) -> bool:
    """Whether a path is one of the reports this pass writes.

    The reports quote the findings of the pass that produced them, so scanning them would make the
    pass find its own text and report it as a defect of the release.
    """
    return path.name in GENERATED_REPORTS


def scan_patterns(
    root: Path, report: HygieneReport, check: str, patterns: Sequence[re.Pattern[str]]
) -> None:
    for path in _text_files(root, TEXT_SUFFIXES):
        if _is_scanner(path) or _is_generated_report(path):
            continue
        try:
            text = path.read_text(encoding="utf-8")
        except UnicodeDecodeError:
            continue
        report.scanned_files += 1
        for number, line in enumerate(text.splitlines(), start=1):
            for pattern in patterns:
                match = pattern.search(line)
                if match:
                    report.add(check, path, number, match.group(0)[:80], root)


def scan_phrases(root: Path, report: HygieneReport) -> None:
    for path in _text_files(root, TEXT_SUFFIXES):
        if _is_scanner(path) or _is_generated_report(path):
            continue
        try:
            text = path.read_text(encoding="utf-8")
        except UnicodeDecodeError:
            continue
        lowered = text.lower()
        for number, line in enumerate(lowered.splitlines(), start=1):
            for phrase in FORBIDDEN_PHRASES:
                if phrase in line:
                    report.add("generated-content-phrase", path, number, phrase, root)


def scan_markdown(root: Path, report: HygieneReport) -> None:
    found = [path.relative_to(root).as_posix() for path in iter_source_files(root, (".md",))]
    report.markdown_files = tuple(found)
    for name in found:
        if name != "README.md":
            report.add(
                "unexpected-markdown",
                root / name,
                1,
                "only README.md is kept in a release",
                root,
            )


def scan_personal_data(root: Path, report: HygieneReport) -> None:
    for path in _text_files(root, (".py", ".yaml", ".yml", ".toml", ".json")):
        if _is_scanner(path) or _is_generated_report(path):
            continue
        try:
            text = path.read_text(encoding="utf-8")
        except UnicodeDecodeError:
            continue
        for number, line in enumerate(text.splitlines(), start=1):
            for pattern in PERSONAL_PATTERNS:
                match = pattern.search(line)
                if not match:
                    continue
                report.add("personal-data", path, number, match.group(0)[:60], root)


def module_names(package_root: Path) -> dict[str, Path]:
    """Dotted name of every module in the package, keyed by name."""
    found: dict[str, Path] = {}
    for path in sorted(package_root.rglob("*.py")):
        relative = path.relative_to(package_root.parent).with_suffix("")
        parts = list(relative.parts)
        if parts[-1] == "__init__":
            parts = parts[:-1]
        found[".".join(parts)] = path
    return found


def imported_modules(root: Path) -> set[str]:
    """Every ``prism.`` module referenced by an import statement anywhere in the tree."""
    referenced: set[str] = set()
    for path in _text_files(root, (".py",)):
        try:
            tree = ast.parse(path.read_text(encoding="utf-8"))
        except SyntaxError as failure:
            raise ResourceError(f"{path} does not parse: {failure}") from failure
        for node in ast.walk(tree):
            if isinstance(node, ast.Import):
                for alias in node.names:
                    if alias.name.startswith("prism"):
                        referenced.add(alias.name)
            elif (
                isinstance(node, ast.ImportFrom) and node.module and node.module.startswith("prism")
            ):
                referenced.add(node.module)
                for alias in node.names:
                    referenced.add(f"{node.module}.{alias.name}")
    return referenced


def scan_unreferenced(package_root: Path, report: HygieneReport, root: Path) -> None:
    names = module_names(package_root)
    report.module_count = len(names)
    referenced = imported_modules(root)
    referenced_prefixes = {value.rsplit(".", 1)[0] for value in referenced} | referenced
    for name, path in names.items():
        if name.endswith(".__init__"):
            continue
        if name == "prism.cli.__main__":
            continue
        parent = name.rsplit(".", 1)[0]
        if name in referenced_prefixes or parent in referenced_prefixes:
            continue
        if name in referenced:
            continue
        report.add(
            "unreferenced-module",
            path,
            1,
            "no module imports this one",
            root,
        )


def _function_bodies(package_root: Path) -> dict[str, list[tuple[str, int]]]:
    bodies: dict[str, list[tuple[str, int]]] = {}
    for path in sorted(package_root.rglob("*.py")):
        try:
            tree = ast.parse(path.read_text(encoding="utf-8"))
        except SyntaxError:
            continue
        for node in ast.walk(tree):
            if not isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
                continue
            if len(node.body) < 6:
                continue
            try:
                segment = ast.get_source_segment(path.read_text(encoding="utf-8"), node)
            except Exception:
                segment = None
            if not segment:
                continue
            digest = _normalise_body(segment)
            bodies.setdefault(digest, []).append((path.as_posix(), node.lineno))
    return {key: value for key, value in bodies.items() if len(value) > 1}


def _normalise_body(source: str) -> str:
    lines = [
        line.strip()
        for line in source.splitlines()
        if line.strip() and not line.strip().startswith("#")
    ]
    return re.sub(r"[A-Za-z_][A-Za-z0-9_]*", "_", "\n".join(lines[1:]))


def scan_duplicate_functions(package_root: Path, report: HygieneReport, root: Path) -> None:
    for sites in _function_bodies(package_root).values():
        first = sites[0]
        for path_text, lineno in sites[1:]:
            report.add(
                "duplicate-function-body",
                Path(path_text),
                lineno,
                f"same body as line {first[1]} of {Path(first[0]).name}",
                root,
            )


def scan_duplicate_files(root: Path, report: HygieneReport, suffixes: Sequence[str]) -> None:
    seen: dict[str, str] = {}
    for path in _text_files(root, suffixes):
        if path.name == "__init__.py":
            continue
        digest = digest_file(path)
        if digest in seen:
            report.add(
                "duplicate-file",
                path,
                1,
                f"identical to {Path(seen[digest]).name}",
                root,
            )
        else:
            seen[digest] = path.as_posix()


def run_hygiene(root: Path, package_root: Path) -> HygieneReport:
    """Run every hygiene check over a checkout."""
    report = HygieneReport()
    scan_patterns(root, report, "absolute-path", ABSOLUTE_PATH_PATTERNS)
    scan_patterns(root, report, "credential-pattern", SECRET_PATTERNS)
    scan_phrases(root, report)
    scan_personal_data(root, report)
    scan_markdown(root, report)
    scan_unreferenced(package_root, report, root)
    scan_duplicate_functions(package_root, report, root)
    scan_duplicate_files(root, report, ("py",))
    return report


def write_dataset_urls(path: Path, extra_lines: Sequence[str] = ()) -> Path:
    """Write the verified resource list.

    Only the resources whose landing page and payload were read back from the source service are
    written with a URL; the resources the study names but does not publish are listed without one,
    because inventing a link for them would be worse than leaving it out. A series submitted on more
    than one platform has one matrix per platform, so every matrix file is listed rather than the
    first one alone.
    """
    lines: list[str] = [
        "# Public resources cited by the auxiliary comparison.",
        "#",
        "# Each entry gives the landing page, the endpoint that was read, and the sample count the",
        "# article prints beside it. Every count below was read back from the source service and",
        "# matched the printed count at the time of the check; the counts in the panel-A resources",
        "# are case counts from the project endpoint and the panel-B counts are sample counts from",
        "# the series header.",
        f"# verified on {RESOURCES[0].verified_on}",
        "",
    ]
    for entry in RESOURCES:
        lines.append(f"[{entry.accession}] {entry.label}")
        lines.append(f"  landing  {entry.landing_url}")
        lines.append(f"  endpoint {entry.download_url}")
        for matrix in entry.matrix_urls():
            if matrix != entry.download_url:
                lines.append(f"  matrix   {matrix}")
        lines.append(
            f"  panel    {entry.panel} | n={entry.n_samples} | assay {entry.assay} | "
            f"license {entry.license}"
        )
        lines.append("")
    lines.append("# Resources named by the study that have no public location")
    for name in clinically_restricted():
        lines.append(f"restricted	{name}")
    lines.extend(extra_lines)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return path


def build_manifest(
    root: Path,
    manifest_path: Path,
    report: HygieneReport,
    extra: Mapping[str, object] | None = None,
    exclude: Sequence[Path] = (),
) -> tuple[Path, tuple[InventoryEntry, ...]]:
    """Write the integrity manifest, keeping the manifest and the other reports out of itself."""
    banned = list(exclude) + [manifest_path]
    entries = inventory(root, exclude=banned)
    body: dict[str, object] = {
        "producer": "prism.audit.integrity",
        "hygiene": {
            "scanned_files": report.scanned_files,
            "module_count": report.module_count,
            "markdown_files": list(report.markdown_files),
            "finding_counts": dict(report.by_check()),
            "clean": report.clean(),
        },
    }
    if extra:
        body.update({str(key): value for key, value in extra.items()})
    written = write_manifest(manifest_path, entries, body)
    return written, tuple(entries)


def manifest_covers(path: Path, entries: Sequence[InventoryEntry]) -> bool:
    """Whether a manifest lists the same files the working tree now holds."""
    payload = json.loads(path.read_text(encoding="utf-8"))
    listed = {
        str(entry["path"]): str(entry["sha256"])
        for entry in payload.get("entries", [])
        if isinstance(entry, dict)
    }
    current = {entry.relative_path: entry.sha256 for entry in entries}
    return listed == current
